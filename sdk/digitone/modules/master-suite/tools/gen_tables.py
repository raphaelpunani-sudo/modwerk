#!/usr/bin/env python3
"""Generate src/ms_tables.h: trig and gain tables for Master Suite.

Pure maths, no firmware data. Run: python3 -B tools/gen_tables.py > src/ms_tables.h
Assumption (unverified): the render runs at 48 kHz. Change FS and regenerate if not.
"""
import math

FS = 48000.0
Q24 = 1 << 24
Q30 = 1 << 30

# Frequency ranges per control: (name, low Hz, high Hz), 128 log-spaced steps.
RANGES = [
    ("FILTER", 20.0, 18000.0),
    ("EQ_LS", 30.0, 450.0),
    ("EQ_LM", 200.0, 2500.0),
    ("EQ_HM", 600.0, 7000.0),
    ("EQ_HS", 1500.0, 16000.0),
]
STEPS = 128
GAIN_STEPS = 61            # -15 .. +15 dB in 0.5 dB steps
Q_STEPS = 128              # filter resonance 0..127


def freq(lo, hi, i):
    return lo * (hi / lo) ** (i / (STEPS - 1))


def q(v):
    """Resonance knob 0..127 -> Q 0.5 .. 12, quadratic so the top is musical."""
    return 0.5 + 11.5 * (v / 127.0) ** 2


def arr(name, values, fmt="%d"):
    out = ["static const int32_t %s[%d] = {" % (name, len(values))]
    line = "   "
    for v in values:
        item = " " + (fmt % v) + ","
        if len(line) + len(item) > 96:
            out.append(line)
            line = "   "
        line += item
    out.append(line)
    out.append("};")
    return "\n".join(out)


print("/* Generated by tools/gen_tables.py. Do not edit by hand. */")
print("#ifndef MS_TABLES_H\n#define MS_TABLES_H\n#include <stdint.h>")
print("#define MS_FS %d\n#define MS_FREQ_STEPS %d\n#define MS_GAIN_STEPS %d\n#define MS_Q_STEPS %d"
      % (int(FS), STEPS, GAIN_STEPS, Q_STEPS))
print("/* 1-cos and sin of 2*pi*f/fs in Q30, per frequency step (1-cos is kept exact: it is tiny at low f) */")
for name, lo, hi in RANGES:
    ws = [2 * math.pi * freq(lo, hi, i) / FS for i in range(STEPS)]
    print(arr("ms_omc_" + name.lower(), [round(2 * math.sin(w / 2) ** 2 * Q30) for w in ws]))
    print(arr("ms_sin_" + name.lower(), [round(math.sin(w) * Q30) for w in ws]))
print("/* Frequency in Hz per step, for the display */")
for name, lo, hi in RANGES:
    print(arr("ms_hz_" + name.lower(), [round(freq(lo, hi, i)) for i in range(STEPS)]))
print("/* A = 10^(dB/40) and sqrt(A) in Q24, per 0.5 dB step from -15 dB */")
gains = [-15.0 + 0.5 * i for i in range(GAIN_STEPS)]
print(arr("ms_a", [round(10 ** (g / 40) * Q24) for g in gains]))
print(arr("ms_sqrt_a", [round(10 ** (g / 80) * Q24) for g in gains]))
print("/* 1/(2Q) in Q24 for the filter resonance knob */")
print(arr("ms_inv2q", [round(Q24 / (2 * q(v))) for v in range(Q_STEPS)]))
print("#endif")
